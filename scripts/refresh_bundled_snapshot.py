#!/usr/bin/env python3
"""Regenerate the station snapshot packed into the app.

The snapshot is what a cold start shows when Radio Browser cannot be reached (common
from mainland China): Chinese-language stations from the mainland, Hong Kong, Taiwan
and Singapore, plus some of the most played stations worldwide. Only stations that
passed Radio Browser's last check and have a stream address are kept.

Usage:
    python3 scripts/refresh_bundled_snapshot.py            # rewrite the Kotlin file
    python3 scripts/refresh_bundled_snapshot.py --check    # print counts, write nothing

Standard library only, so it runs on a stock CI runner.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.parse
import urllib.request
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "app/sharedLogic/src/commonMain/kotlin/app/tuneroam/radio/data/remote/BundledSnapshotJson.kt"
MIRRORS = ["de1.api.radio-browser.info", "de2.api.radio-browser.info"]
USER_AGENT = "TuneRoam-snapshot (app.tuneroam.radio)"

# (country code, how many, only Chinese-language stations)
REGIONS = [
    ("CN", 50, False),
    ("TW", 25, False),
    ("HK", 20, False),
    ("SG", 15, True),
]
GLOBAL_COUNT = 40

# The fields StationDto reads; anything else Radio Browser sends is dropped.
FIELDS = [
    "stationuuid", "name", "url", "url_resolved", "homepage", "favicon", "tags",
    "country", "countrycode", "language", "codec", "bitrate", "hls", "lastcheckok", "clickcount",
]
CHINESE = ("chinese", "mandarin", "cantonese")

HEADER = '''package app.tuneroam.radio.data.remote

/** Stations shipped with the app so a cold start in mainland China still has something to play. */
// Generated by scripts/refresh_bundled_snapshot.py. Do not edit by hand.
internal val BUNDLED_SNAPSHOT_JSON: String = """
'''
FOOTER = '\n""".trim()\n'


def get(host: str, path: str, params: dict[str, str] | None = None) -> list[dict]:
    query = f"?{urllib.parse.urlencode(params)}" if params else ""
    request = urllib.request.Request(f"https://{host}{path}{query}", headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def pick_mirror() -> str:
    for host in MIRRORS:
        try:
            get(host, "/json/stats")
            return host
        except Exception as error:  # noqa: BLE001 - try the next mirror whatever went wrong
            print(f"{host}: {error}", file=sys.stderr)
    sys.exit("No Radio Browser mirror answered.")


def usable(station: dict) -> bool:
    return bool(station.get("stationuuid")) and station.get("lastcheckok") == 1 and bool(
        (station.get("url_resolved") or station.get("url") or "").strip()
    )


def speaks_chinese(station: dict) -> bool:
    language = (station.get("language") or "").lower()
    return any(name in language for name in CHINESE)


def collect(host: str) -> list[dict]:
    chosen: dict[str, dict] = {}
    for code, count, chinese_only in REGIONS:
        found = get(host, "/json/stations/search", {
            "countrycode": code,
            "hidebroken": "true",
            "order": "clickcount",
            "reverse": "true",
            "limit": str(count * 4),
        })
        kept = [s for s in found if usable(s) and (not chinese_only or speaks_chinese(s))]
        for station in kept[:count]:
            chosen.setdefault(station["stationuuid"], station)
    popular = get(host, f"/json/stations/topclick/{GLOBAL_COUNT * 3}")
    added = 0
    for station in popular:
        if added >= GLOBAL_COUNT:
            break
        if usable(station) and station["stationuuid"] not in chosen:
            chosen[station["stationuuid"]] = station
            added += 1
    return [{field: station.get(field, "" if field not in ("bitrate", "hls", "lastcheckok", "clickcount") else 0)
             for field in FIELDS} for station in chosen.values()]


def kotlin_source(stations: list[dict]) -> str:
    payload = json.dumps(stations, ensure_ascii=False, separators=(", ", ": "))
    # A Kotlin raw string still expands templates; keep any literal dollar sign literal.
    payload = payload.replace("$", "${'$'}")
    return HEADER + payload + FOOTER


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="print what would be written, change nothing")
    args = parser.parse_args()

    host = pick_mirror()
    stations = collect(host)
    counts = Counter(station["countrycode"] for station in stations)
    print(f"{len(stations)} stations from {host}: {dict(counts.most_common())}")
    if len(stations) < 100:
        sys.exit("Fewer than 100 stations; refusing to replace the snapshot (the app's tests expect at least 100).")
    if args.check:
        return
    TARGET.write_text(kotlin_source(stations), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
